package plugin;

import java.io.File;
import java.util.List;
import java.util.logging.Logger;

import model.board.Board;
import model.board.MapGenerator;

// Plugin loader buat MapGenerator
public class MapPluginLoader extends PluginLoader<MapGenerator> {

    private static final Logger LOGGER = Logger.getLogger(MapPluginLoader.class.getName());

    @Override
    protected Class<MapGenerator> getPluginInterface() {
        return MapGenerator.class;
    }

    
    public Board loadAndGenerate(File jarFile, String className) throws PluginLoadException {
        MapGenerator generator = loadPlugin(jarFile, className);
        Board board = generator.generateBoard();
        assert board != null : "MapGenerator.generateBoard() returned null for: " + className;
        LOGGER.info("Board generated by plugin '" + generator.getGeneratorName() + "'");
        return board;
    }

    public MapGenerator loadFirstGenerator(File jarFile) throws PluginLoadException {
        List<MapGenerator> generators = loadAllFromJar(jarFile);
        if (generators.isEmpty()) {
            throw new PluginLoadException(
                "No MapGenerator implementation found in: " + jarFile.getName()
            );
        }
        if (generators.size() > 1) {
            LOGGER.warning("Multiple MapGenerators found, using first: "
                + generators.get(0).getGeneratorName());
        }
        return generators.get(0);
    }
}
